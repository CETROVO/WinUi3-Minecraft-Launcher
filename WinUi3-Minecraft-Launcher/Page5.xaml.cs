        private async Task LoadFabricVersionsAsync()
        {
            try
            {
                var json = await Http.GetStringAsync($"https://meta.fabricmc.net/v2/versions/loader/{_mcVersion}");
                using var doc = JsonDocument.Parse(json);
                var versionList = new List<string>();
                foreach (var element in doc.RootElement.EnumerateArray())
                {
                    var ver = element.GetProperty("loader").GetProperty("version").GetString() ?? "";
                    if (!string.IsNullOrEmpty(ver)) versionList.Add(ver);
                }
                DispatcherQueue.TryEnqueue(() =>
                {
                    foreach (var ver in versionList) FabricVersionCombo.Items.Add(ver);
                    if (FabricVersionCombo.Items.Count > 0) FabricVersionCombo.SelectedIndex = 0;
                });
            }
            catch { DispatcherQueue.TryEnqueue(() => FabricVersionCombo.PlaceholderText = "网络加载失败"); }
        }

        private async Task FetchFabricApiVersionsAsync()
        {
            try
            {
                var url = $"https://api.modrinth.com/v2/project/fabric-api/version?game_versions=[\"{_mcVersion}\"]&loaders=[\"fabric\"]";
                var json = await Http.GetStringAsync(url);
                using var doc = JsonDocument.Parse(json);
                var apiVersions = new List<string>();
                foreach (var element in doc.RootElement.EnumerateArray())
                {
                    var verNum = element.GetProperty("version_number").GetString() ?? "";
                    if (!string.IsNullOrEmpty(verNum)) apiVersions.Add(verNum);
                }
                DispatcherQueue.TryEnqueue(() =>
                {
                    foreach (var ver in apiVersions) FabricApiVersionCombo.Items.Add(ver);
                    if (FabricApiVersionCombo.Items.Count > 0) FabricApiVersionCombo.SelectedIndex = 0;
                });
            }
            catch { DispatcherQueue.TryEnqueue(() => FabricApiVersionCombo.PlaceholderText = "网络加载失败"); }
        }

