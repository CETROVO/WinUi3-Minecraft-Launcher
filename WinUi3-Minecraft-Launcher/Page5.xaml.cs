        private async void StartDownloadButton_Click(object sender, RoutedEventArgs e)
        {
            if (_isDownloading) return;

            var mcDir = LauncherState.CurrentMinecraftPath;
            if (string.IsNullOrEmpty(mcDir)) { await ShowDialogAsync("提示", "请先在「启动」页选择一个 .minecraft 文件夹。"); return; }

            var targetName = VersionNameTextBox.Text.Trim();
            if (string.IsNullOrEmpty(targetName)) targetName = _mcVersion;

            if (_selectedLoaderName == "原版" && LoaderListView.SelectedItem is LoaderItem item && item.Name != "原版" && item.Name != "Java")
            {
                var confirm = await ShowDialogAsync("提示", $"你当前正在查看 {item.Name} 页面，但上方开关未启用。\n\n是否仅下载纯净原版？", true);
                if (confirm != ContentDialogResult.Primary) return;
            }

            string targetVersionDir = Path.Combine(mcDir, "versions", targetName);
            if (Directory.Exists(targetVersionDir))
            {
                var confirm = await ShowDialogAsync("版本已存在", $"目标版本 {targetName} 已经在本地存在！\n\n是否覆盖安装？（旧版本文件将被强制删除）", true);
                if (confirm != ContentDialogResult.Primary) return;

                try { Directory.Delete(targetVersionDir, true); }
                catch (Exception ex) { await ShowDialogAsync("删除旧版本失败", $"无法删除旧版本，请关闭占用文件的程序重试。\n{ex.Message}"); return; }
            }

            _isDownloading = true;
            StartDownloadButton.IsEnabled = false;

            _downloadDialog = CreateDownloadDialog();
            _ = _downloadDialog.ShowAsync();
            _speedCts = new CancellationTokenSource();
            _ = StartNetworkSpeedMonitor(_speedCts.Token);

            try
            {
                var path = new MinecraftPath(mcDir);
                var launcher = new MinecraftLauncher(path);

                launcher.FileProgressChanged += (s, e) =>
                {
                    int remaining = e.TotalTasks - e.ProgressedTasks;
                    string fileInfo = $"正在下载: {e.Name} (剩余 {remaining} 个文件)";
                    UpdateDownloadUI(null, fileInfo, -1);
                };

                launcher.ByteProgressChanged += (s, e) =>
                {
                    if (e.TotalBytes > 0)
                    {
                        double percent = (double)e.ProgressedBytes / e.TotalBytes * 100;
                        double mappedPercent = percent * 0.6;
                        UpdateDownloadUI(null, null, mappedPercent);
                    }
                };

                if (_selectedLoaderName == "Fabric" && !string.IsNullOrEmpty(_selectedLoaderVersion))
                {
                    UpdateDownloadUI("正在获取 Fabric JSON...", "", 2);
                    await InstallFabricViaApiAsync(mcDir, _mcVersion, _selectedLoaderVersion, targetName);

                    UpdateDownloadUI("正在补全游戏资源与依赖库...", "", 5);
                    await launcher.InstallAsync(targetName);
                }
                else
                {
                    UpdateDownloadUI("正在下载原版文件...", "", 5);
                    await launcher.InstallAsync(_mcVersion);
                    if (_mcVersion != targetName)
                    {
                        UpdateDownloadUI("正在修改版本名称...", "", 60);
                        RenameVersionFolder(mcDir, _mcVersion, targetName);
                    }
                }

                UpdateDownloadUI("游戏核心文件处理完成", "", 60);

                if (_selectedLoaderName == "Fabric" && !string.IsNullOrEmpty(_selectedFabricApiVersion))
                {
                    UpdateDownloadUI("正在下载 Fabric API...", "", 80);
                    await DownloadFabricApiAsync(mcDir, _mcVersion, _selectedFabricApiVersion, targetName);
                }

                UpdateDownloadUI("安装完成！", "", 100);
                await Task.Delay(1000);

                _speedCts.Cancel();
                _downloadDialog.Hide();
                _downloadDialog = null;

                await ShowDialogAsync("安装成功", $"版本 {targetName} 已经准备就绪！");
                if (Frame.CanGoBack) Frame.GoBack();
            }
            catch (Exception ex)
            {
                if (_speedCts != null) _speedCts.Cancel();
                if (_downloadDialog != null) { _downloadDialog.Hide(); _downloadDialog = null; }

                await ShowDialogAsync("安装失败", $"发生错误：\n{ex.Message}");
            }
            finally
            {
                _isDownloading = false;
                StartDownloadButton.IsEnabled = true;
            }
        }

        private async Task InstallFabricViaApiAsync(string mcDir, string mcVersion, string loaderVersion, string targetName)
        {
            string url = $"https://meta.fabricmc.net/v2/versions/loader/{mcVersion}/{loaderVersion}/profile/json";
            string json = await Http.GetStringAsync(url);

            var node = JsonNode.Parse(json);
            if (node is JsonObject obj)
            {
                obj["id"] = targetName;
                json = obj.ToJsonString();
            }

            var versionDir = Path.Combine(mcDir, "versions", targetName);
            Directory.CreateDirectory(versionDir);
            var jsonPath = Path.Combine(versionDir, $"{targetName}.json");
            await File.WriteAllTextAsync(jsonPath, json);
        }

