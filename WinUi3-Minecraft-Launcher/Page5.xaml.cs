        private async Task LoadNeoForgeVersionsAsync()
        {
            try
            {
                // 1.20.1 走 net/neoforged/forge，其余走 net/neoforged/neoforge
                string apiUrl = _mcVersion == "1.20.1"
                    ? "https://maven.neoforged.net/api/maven/versions/releases/net/neoforged/forge"
                    : "https://maven.neoforged.net/api/maven/versions/releases/net/neoforged/neoforge";

                var json = await Http.GetStringAsync(apiUrl);
                using var doc = JsonDocument.Parse(json);
                var versionsObj = doc.RootElement.GetProperty("versions");
                var versionList = new List<string>();

                string mcVerPrefix = _mcVersion;
                if (mcVerPrefix == "1.20.1") mcVerPrefix = "47.1";
                else if (mcVerPrefix.StartsWith("1.")) mcVerPrefix = mcVerPrefix.Substring(2);

                if (mcVerPrefix == "21") mcVerPrefix = "21.0";

                foreach (var item in versionsObj.EnumerateArray())
                {
                    var ver = item.GetString() ?? "";
                    if (ver.StartsWith(mcVerPrefix + ".") || ver.StartsWith(mcVerPrefix + "-"))
                        versionList.Add(ver);
                }

                DispatcherQueue.TryEnqueue(() =>
                {
                    NeoForgeVersionCombo.Items.Clear();
                    versionList.Reverse();
                    foreach (var ver in versionList) NeoForgeVersionCombo.Items.Add(ver);

                    if (NeoForgeVersionCombo.Items.Count > 0)
                        NeoForgeVersionCombo.SelectedIndex = 0;
                    else
                        NeoForgeVersionCombo.PlaceholderText = "未找到适配版本";
                });
            }
            catch (Exception ex)
            {
                System.Diagnostics.Debug.WriteLine($"[NeoForge Error] {ex.Message}");
                DispatcherQueue.TryEnqueue(() => NeoForgeVersionCombo.PlaceholderText = "网络加载失败");
            }
        }

