        private async void DownloadJavaButton_Click(object sender, RoutedEventArgs e)
        {
            if (sender is not Button btn) return;

            var selectedItem = JavaVersionCombo.SelectedItem as ComboBoxItem;
            if (selectedItem == null || selectedItem.Tag == null) return;
            string javaVer = selectedItem.Tag.ToString()!;

            btn.IsEnabled = false;
            JavaDownloadProgress.Visibility = Visibility.Visible;
            JavaStatusText.Visibility = Visibility.Visible;
            JavaStatusText.Text = "正在获取下载链接...";
            JavaDownloadProgress.Value = 0;

            try
            {
                string apiUrl = $"https://api.adoptium.net/v3/assets/latest/{javaVer}/hotspot?architecture=x64&image_type=jdk&os=windows&vendor=eclipse";
                var json = await Http.GetStringAsync(apiUrl);
                using var doc = JsonDocument.Parse(json);
                var downloadUrl = doc.RootElement[0].GetProperty("binary").GetProperty("package").GetProperty("link").GetString();
                var fileName = doc.RootElement[0].GetProperty("binary").GetProperty("package").GetProperty("name").GetString();

                if (string.IsNullOrEmpty(downloadUrl) || string.IsNullOrEmpty(fileName))
                    throw new Exception("未能获取到 Java 下载链接。");

                JavaStatusText.Text = "正在下载 Java 压缩包...";
                var response = await Http.GetAsync(downloadUrl, HttpCompletionOption.ResponseHeadersRead);
                response.EnsureSuccessStatusCode();

                var totalBytes = response.Content.Headers.ContentLength ?? -1L;
                using var contentStream = await response.Content.ReadAsStreamAsync();

                string tempDir = Path.Combine(Path.GetTempPath(), "WML_Java_Download");
                Directory.CreateDirectory(tempDir);
                string zipPath = Path.Combine(tempDir, fileName);

                using (var fileStream = new FileStream(zipPath, FileMode.Create, FileAccess.Write, FileShare.None))
                {
                    var buffer = new byte[81920];
                    long totalRead = 0;
                    int bytesRead;

                    while ((bytesRead = await contentStream.ReadAsync(buffer, 0, buffer.Length)) > 0)
                    {
                        await fileStream.WriteAsync(buffer, 0, bytesRead);
                        totalRead += bytesRead;

                        if (totalBytes > 0)
                        {
                            double percentage = (double)totalRead / totalBytes * 100;
                            DispatcherQueue.TryEnqueue(() =>
                            {
                                JavaDownloadProgress.Value = percentage;
                                JavaStatusText.Text = $"正在下载... {percentage:F1}%";
                            });
                        }
                    }
                }

                JavaStatusText.Text = "正在解压 Java 运行环境...";
                JavaDownloadProgress.IsIndeterminate = true;

                // 🚨 修改：指向 %UserProfile%\AppData\Local\Java\{JavaVer}
                string localAppData = Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData);
                string extractDir = Path.Combine(localAppData, "Java", javaVer);

                if (Directory.Exists(extractDir))
                {
                    try { Directory.Delete(extractDir, true); } catch { }
                }
                Directory.CreateDirectory(extractDir);

                ZipFile.ExtractToDirectory(zipPath, extractDir, true);

                try { File.Delete(zipPath); } catch { }

                JavaStatusText.Text = "✅ Java 安装完成！现在可以返回启动页游玩了。";
                JavaDownloadProgress.Value = 100;
                JavaDownloadProgress.IsIndeterminate = false;

                await ShowDialogAsync("安装成功", $"Java {javaVer} 已经成功安装到您的电脑！\n\n路径: {extractDir}\n\n启动器会自动检测并使用它。");
            }
            catch (Exception ex)
            {
                JavaStatusText.Text = $"❌ 下载或解压失败：{ex.Message}";
                JavaDownloadProgress.Visibility = Visibility.Collapsed;
            }
            finally
            {
                btn.IsEnabled = true;
            }
        }

