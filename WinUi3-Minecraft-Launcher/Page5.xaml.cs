        private async Task RunForgeInstallerAsync(string mcDir, string loaderType, string mcVersion, string loaderVersion, string targetName)
        {
            string installerUrl;
            string installerName;

            if (loaderType == "forge")
            {
                installerUrl = $"https://bmclapi2.bangbang93.com/maven/net/minecraftforge/forge/{mcVersion}-{loaderVersion}/forge-{mcVersion}-{loaderVersion}-installer.jar";
                installerName = $"forge-{mcVersion}-{loaderVersion}-installer.jar";
            }
            else // neoforge
            {
                if (mcVersion == "1.20.1")
                {
                    installerUrl = $"https://maven.neoforged.net/releases/net/neoforged/forge/{mcVersion}-{loaderVersion}/forge-{mcVersion}-{loaderVersion}-installer.jar";
                    installerName = $"forge-{mcVersion}-{loaderVersion}-installer.jar";
                }
                else
                {
                    installerUrl = $"https://maven.neoforged.net/releases/net/neoforged/neoforge/{loaderVersion}/neoforge-{loaderVersion}-installer.jar";
                    installerName = $"neoforge-{loaderVersion}-installer.jar";
                }
            }

            string tempJar = Path.Combine(Path.GetTempPath(), installerName);
            var bytes = await Http.GetByteArrayAsync(installerUrl);
            await File.WriteAllBytesAsync(tempJar, bytes);

            UpdateDownloadUI("正在静默安装加载器核心 (需1-2分钟)...", "", 80);

            string? javaPath = JavaFinder.FindJavaByMajorVersion(JavaFinder.GetRequiredJavaMajorVersion(mcDir, mcVersion)) ?? JavaFinder.FindJava();
            if (string.IsNullOrEmpty(javaPath)) throw new Exception("找不到可用的 Java 环境来执行安装器。");

            var psi = new ProcessStartInfo
            {
                FileName = javaPath,
                Arguments = $"-jar \"{tempJar}\" --installClient \"{mcDir}\"",
                UseShellExecute = false,
                CreateNoWindow = true,
                RedirectStandardOutput = true,
                RedirectStandardError = true
            };

            using var process = Process.Start(psi);
            if (process != null)
            {
                await process.WaitForExitAsync();
                if (process.ExitCode != 0) throw new Exception("加载器安装器执行失败，请检查 Java 环境是否正常。");
            }

            try { File.Delete(tempJar); } catch { }

            string expectedDir = Path.Combine(mcDir, "versions", $"{mcVersion}-{loaderType}-{loaderVersion}");
            string targetDir = Path.Combine(mcDir, "versions", targetName);

            if (Directory.Exists(expectedDir) && !Directory.Exists(targetDir))
            {
                Directory.Move(expectedDir, targetDir);
                string oldJson = Path.Combine(targetDir, $"{mcVersion}-{loaderType}-{loaderVersion}.json");
                string newJson = Path.Combine(targetDir, $"{targetName}.json");
                if (File.Exists(oldJson))
                {
                    var text = await File.ReadAllTextAsync(oldJson);
                    text = text.Replace($"\"id\":\"{mcVersion}-{loaderType}-{loaderVersion}\"", $"\"id\":\"{targetName}\"");
                    await File.WriteAllTextAsync(newJson, text);
                    File.Delete(oldJson);
                }
            }
        }

        private async Task RunOptiFineInstallerAsync(string mcDir, string mcVersion, string optifineVer, string targetName)
        {
            var parts = optifineVer.Split('_');
            string type = parts[0];
            string patch = parts[1];

            string installerUrl = $"https://bmclapi2.bangbang93.com/optifine/{mcVersion}/{type}/{patch}";
            string installerName = $"OptiFine_{mcVersion}_{optifineVer}.jar";

            string tempJar = Path.Combine(Path.GetTempPath(), installerName);
            var bytes = await Http.GetByteArrayAsync(installerUrl);
            await File.WriteAllBytesAsync(tempJar, bytes);

            UpdateDownloadUI("正在静默安装 OptiFine...", "", 80);

            string? javaPath = JavaFinder.FindJavaByMajorVersion(JavaFinder.GetRequiredJavaMajorVersion(mcDir, mcVersion)) ?? JavaFinder.FindJava();
            if (string.IsNullOrEmpty(javaPath)) throw new Exception("找不到可用的 Java 环境来执行安装器。");

            var psi = new ProcessStartInfo
            {
                FileName = javaPath,
                Arguments = $"-jar \"{tempJar}\" --installClient \"{mcDir}\"",
                UseShellExecute = false,
                CreateNoWindow = true,
                RedirectStandardOutput = true,
                RedirectStandardError = true
            };

            using var process = Process.Start(psi);
            if (process != null)
            {
                await process.WaitForExitAsync();
                if (process.ExitCode != 0) throw new Exception("OptiFine 安装器执行失败，请检查 Java 环境是否正常。");
            }

            try { File.Delete(tempJar); } catch { }

            string expectedDir = Path.Combine(mcDir, "versions", $"{mcVersion}-OptiFine_{optifineVer}");
            string targetDir = Path.Combine(mcDir, "versions", targetName);

            if (Directory.Exists(expectedDir) && !Directory.Exists(targetDir))
            {
                Directory.Move(expectedDir, targetDir);
                string oldJson = Path.Combine(targetDir, $"{mcVersion}-OptiFine_{optifineVer}.json");
                string newJson = Path.Combine(targetDir, $"{targetName}.json");
                if (File.Exists(oldJson))
                {
                    var text = await File.ReadAllTextAsync(oldJson);
                    text = text.Replace($"\"id\":\"{mcVersion}-OptiFine_{optifineVer}\"", $"\"id\":\"{targetName}\"");
                    await File.WriteAllTextAsync(newJson, text);
                    File.Delete(oldJson);
                }
            }
        }

