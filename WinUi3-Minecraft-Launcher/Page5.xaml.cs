        private void UpdateToggleState(bool isOn, string name)
        {
            if (_isUpdatingToggles) return;

            if (isOn)
            {
                _isUpdatingToggles = true;
                // 🚨 核心修复：只关掉“别人”，放过自己
                if (name != "Fabric" && FabricToggle.IsOn) FabricToggle.IsOn = false;
                if (name != "Quilt" && QuiltToggle.IsOn) QuiltToggle.IsOn = false;
                if (name != "Forge" && ForgeToggle.IsOn) ForgeToggle.IsOn = false;
                if (name != "NeoForge" && NeoForgeToggle.IsOn) NeoForgeToggle.IsOn = false;
                if (name != "OptiFine" && OptiFineToggle.IsOn) OptiFineToggle.IsOn = false;
                _isUpdatingToggles = false;

                _selectedLoaderName = name;
                UpdateVersionName();
            }
            else
            {
                // 如果用户主动关掉了当前的开关，检查是否还有其他开着的
                if (!FabricToggle.IsOn && !QuiltToggle.IsOn && !ForgeToggle.IsOn && !NeoForgeToggle.IsOn && !OptiFineToggle.IsOn)
                {
                    _selectedLoaderName = "原版";
                    UpdateVersionName();
                }
            }
        }

