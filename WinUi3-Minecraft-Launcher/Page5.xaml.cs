        private void UpdateDownloadUI(string? status, string? fileInfo, double progress)
        {
            DispatcherQueue.TryEnqueue(() =>
            {
                if (status != null && _statusText != null) _statusText.Text = status;
                if (fileInfo != null && _fileInfoText != null) _fileInfoText.Text = fileInfo;
                if (progress >= 0 && _progressBar != null && _percentText != null) { _progressBar.Value = progress; _percentText.Text = $"{progress:F0}%"; }
            });
        }

        private async Task StartNetworkSpeedMonitor(CancellationToken token)
        {
            long lastBytes = 0; bool isFirst = true;
            while (!token.IsCancellationRequested)
            {
                long currentBytes = 0;
                try
                {
                    foreach (var ni in NetworkInterface.GetAllNetworkInterfaces())
                        if (ni.OperationalStatus == OperationalStatus.Up && ni.NetworkInterfaceType != NetworkInterfaceType.Loopback)
                            currentBytes += ni.GetIPStatistics().BytesReceived;
                }
                catch { }

                if (isFirst) { lastBytes = currentBytes; isFirst = false; }
                else
                {
                    long delta = currentBytes - lastBytes; lastBytes = currentBytes;
                    double speedKb = delta / 1024.0;
                    string speedStr = speedKb > 1024 ? $"{speedKb / 1024:F2} MB/s" : $"{speedKb:F1} KB/s";
                    DispatcherQueue.TryEnqueue(() => { if (_speedText != null) _speedText.Text = speedStr; });
                }
                await Task.Delay(1000, token);
            }
        }

        private void RenameVersionFolder(string mcDir, string oldName, string newName)
        {
            var oldDir = Path.Combine(mcDir, "versions", oldName);
            var newDir = Path.Combine(mcDir, "versions", newName);
            if (Directory.Exists(newDir)) throw new Exception($"重命名失败：目标文件夹 {newName} 已存在。");
            if (!Directory.Exists(oldDir)) return;

            Directory.Move(oldDir, newDir);
            var oldJson = Path.Combine(newDir, $"{oldName}.json");
            var newJson = Path.Combine(newDir, $"{newName}.json");
            if (File.Exists(oldJson))
            {
                var jsonStr = File.ReadAllText(oldJson).Replace($"\"id\":\"{oldName}\"", $"\"id\":\"{newName}\"");
                File.WriteAllText(newJson, jsonStr);
                File.Delete(oldJson);
            }
        }

        private async Task DownloadFabricApiAsync(string mcDir, string mcVersion, string apiVersion, string targetName)
        {
            var url = $"https://api.modrinth.com/v2/project/fabric-api/version?game_versions=[\"{mcVersion}\"]&loaders=[\"fabric\"]";
            var json = await Http.GetStringAsync(url);
            using var doc = JsonDocument.Parse(json);
            string? downloadUrl = null, fileName = null;
            foreach (var ver in doc.RootElement.EnumerateArray())
            {
                if (ver.GetProperty("version_number").GetString() == apiVersion)
                {
                    var files = ver.GetProperty("files");
                    if (files.GetArrayLength() > 0) { downloadUrl = files[0].GetProperty("url").GetString(); fileName = files[0].GetProperty("filename").GetString(); break; }
                }
            }
            if (string.IsNullOrEmpty(downloadUrl) || string.IsNullOrEmpty(fileName)) throw new Exception("找不到 Fabric API 的下载直链");

            var modsDir = Path.Combine(mcDir, "versions", targetName, "mods");
            Directory.CreateDirectory(modsDir);
            var savePath = Path.Combine(modsDir, fileName);
            var bytes = await Http.GetByteArrayAsync(downloadUrl);
            await File.WriteAllBytesAsync(savePath, bytes);
        }

        private async Task<ContentDialogResult> ShowDialogAsync(string title, string message, bool isConfirm = false)
        {
            if (this.XamlRoot == null) return ContentDialogResult.None;
            var dialog = new ContentDialog { Title = title, Content = new TextBlock { Text = message, TextWrapping = TextWrapping.Wrap }, XamlRoot = this.XamlRoot };
            if (isConfirm) { dialog.PrimaryButtonText = "继续"; dialog.CloseButtonText = "取消"; }
            else { dialog.CloseButtonText = "确定"; }
            try { return await dialog.ShowAsync(); } catch { return ContentDialogResult.None; }
        }
